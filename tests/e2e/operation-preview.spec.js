import {test,expect} from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { chooseTheme } from "./theme-helper.js";
test("统计示例独立显示且返回后保留文件",async({page},info)=>{
  await page.goto('/');
  await page.locator('input[type=file]').setInputFiles({name:'待处理测试.txt',mimeType:'text/plain',buffer:Buffer.from('客户名称：虚构测试企业')});
  await expect(page.getByRole('button',{name:'生成脱敏文件',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'操作记录',exact:true}).click();
  const drawer=page.getByRole('dialog',{name:'操作记录',exact:true});
  await drawer.getByRole('button',{name:'统计预览'}).click();
  const preview=page.getByRole('region',{name:'使用统计设计预览'});
  await expect(preview).toBeVisible();
  await expect(page.locator('.app-main')).toBeHidden();
  await expect(page.locator('.app-main')).toHaveCSS('display','none');
  await expect(preview.locator('.usage-tile')).toHaveCount(4);
  await expect(preview.getByRole('button',{name:'最近 30 天'})).toHaveAttribute('aria-pressed','true');
  await expect(preview.locator('.usage-summary')).toContainText('近 30 天处理');
  await expect(preview.locator('.usage-rate strong')).toContainText('%');
  const detail=preview.locator('.usage-detail');
  await expect(detail.locator('.usage-table')).toBeHidden();
  await preview.locator('.usage-tile').filter({hasText:'失败操作'}).getByRole('button',{name:'查看'}).click();
  await expect(detail.getByRole('button',{name:'取消筛选 失败操作'})).toBeVisible();
  await expect(detail.locator('.usage-table tbody tr').first()).toContainText('失败');
  await detail.getByRole('button',{name:'取消筛选 失败操作'}).click();
  await expect(detail.locator('.usage-table tbody tr')).toHaveCount(10);
  await expect(detail.locator('.usage-mobile .operation-list > li')).toHaveCount(10);
  await preview.getByRole('button',{name:'下一页',exact:true}).click();
  await expect(preview.getByRole('button',{name:'上一页',exact:true})).toBeEnabled();
  await preview.getByRole('button',{name:/^查看示例员工甲的明细/}).click();
  await expect(preview.getByRole('button',{name:'上一页',exact:true})).toBeDisabled();
  await expect(detail.locator('.usage-table tbody tr').first()).toContainText('示例员工甲');
  await detail.getByRole('button',{name:'取消筛选 示例员工甲'}).click();
  await detail.getByLabel('只看异常').check();
  await expect(detail.locator('.usage-table tbody tr').first()).not.toContainText('已发起');
  await detail.getByLabel('只看异常').uncheck();
  await preview.locator('.usage-trend__column').nth(20).click();
  await expect(detail.locator('.usage-chip')).toBeVisible();
  await detail.locator('.usage-chip').click();
  await preview.locator('.usage-filters > summary').click();
  await preview.getByLabel('用户',{exact:true}).selectOption('example-甲');
  await expect(preview.locator('.usage-filters > summary')).toContainText('筛选（1）');
  await expect(preview.locator('.usage-rank').first().locator('li')).toHaveCount(1);
  await preview.getByLabel('用户',{exact:true}).selectOption('');
  await preview.getByRole('button',{name:'最近 60 天'}).click();
  await expect(preview.locator('.usage-trend__column')).toHaveCount(9);
  await preview.getByRole('button',{name:'最近 30 天'}).click();
  await expect(preview.locator('.usage-trend__column')).toHaveCount(30);
  for(const theme of ['light','dark','system']){await chooseTheme(page,theme);expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);await page.screenshot({animations:"disabled",path:path.join(os.tmpdir(),`usage-preview-${info.project.name}-${theme}.png`)});}
  const exportExample=page.waitForEvent('download');await preview.getByRole('link',{name:'导出示例记录'}).click();const example=await exportExample;expect(example.suggestedFilename()).toContain('示例');expect(await fs.readFile(await example.path(),'utf8')).toContain('虚构示例');
  expect(await page.evaluate(async()=> (await (await fetch('/api/v1/operation-events')).json()).records.some(r=>r.userId?.startsWith('example')))).toBe(false);
  await preview.getByRole('button',{name:'返回文件处理'}).click();
  await expect(page.locator('.app-main')).toBeVisible();
  await expect(page.getByRole('button',{name:'生成脱敏文件',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'操作记录',exact:true})).toBeFocused();
});
